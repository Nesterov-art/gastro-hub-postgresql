-- Задание 3. Топ-3 заведения, где чаще всего менялся менеджер
-- за весь период.
--
-- В cafe.restaurant_manager_work_dates одна строка — это один период
-- работы одного менеджера в одном заведении. Значит количество строк
-- по заведению равно количеству управлявших им менеджеров.
--
-- Трактовка: считается количество менеджеров, работавших в заведении.
-- Если под «сколько раз менялся менеджер» понимать число переходов
-- от одного менеджера к другому, нужно взять COUNT(*) - 1.
--
-- По данным проекта первое место делят 8 заведений с результатом 8.
-- LIMIT 3 выводит три из них — в соответствии с форматом задания.
SELECT r.cafe_name,
       COUNT(*) AS manager_changes
FROM cafe.restaurant_manager_work_dates w
JOIN cafe.restaurants r USING (restaurant_uuid)
GROUP BY r.cafe_name
ORDER BY manager_changes DESC
LIMIT 3;
