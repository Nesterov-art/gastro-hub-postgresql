-- Задание 6. Повышение цен на капучино на 20%.
--
-- Пояснение к решению:
--
-- 1. Всё выполняется внутри одной явной транзакции. Пока она не
--    зафиксирована, новые цены не видны другим сессиям, а взятые
--    блокировки продолжают действовать.
--
-- 2. Строки обновляемых заведений блокируются заранее, командой
--    SELECT ... FOR UPDATE. Это блокировка уровня строки: чужие
--    UPDATE, DELETE и SELECT ... FOR UPDATE по этим строкам встанут
--    в ожидание, а обычный SELECT продолжит читать данные — Postgres
--    отдаст ему предыдущую версию строки (MVCC). Это и требуется:
--    менять цены параллельно нельзя, читать меню — можно.
--
-- 3. Блокировка берётся отдельным запросом до UPDATE. Сам UPDATE тоже
--    блокирует строки, но только в момент записи: между чтением старых
--    цен и записью новых остался бы зазор, в который могла бы
--    вклиниться чужая транзакция.
--
-- 4. Выбран именно строчный уровень блокировки, а не LOCK TABLE:
--    заведения, где цены не меняются, должны остаться полностью
--    доступными, а блокировка таблицы заморозила бы их все.
--
-- 5. FOR UPDATE, а не FOR SHARE: разделяемая блокировка не пустила бы
--    чужой UPDATE, но пустила бы другой FOR SHARE, и две транзакции
--    могли бы заблокировать друг друга при попытке записи.
--
-- 6. Новые цены считаются в отдельном CTE, затем UPDATE ... FROM
--    связывает их с обновляемыми строками по restaurant_uuid.
--    jsonb_set меняет только цену капучино по пути {Кофе,Капучино},
--    остальное меню остаётся нетронутым.
--
-- 7. Фильтр по наличию капучино написан через IS NOT NULL, а не через
--    оператор существования ключа ?: знак вопроса многие клиенты
--    (в том числе DBeaver) принимают за placeholder параметра запроса.

BEGIN;

-- Блокируем строки заведений, в меню которых есть капучино
SELECT restaurant_uuid,
       cafe_name,
       menu -> 'Кофе' ->> 'Капучино' AS old_price
FROM cafe.restaurants
WHERE (menu -> 'Кофе' ->> 'Капучино') IS NOT NULL
FOR UPDATE;

-- Считаем новые цены и обновляем меню
WITH new_prices AS (
    SELECT restaurant_uuid,
           ROUND((menu -> 'Кофе' ->> 'Капучино')::numeric * 1.2, 2) AS new_price
    FROM cafe.restaurants
    WHERE (menu -> 'Кофе' ->> 'Капучино') IS NOT NULL
)
UPDATE cafe.restaurants r
SET menu = jsonb_set(r.menu, '{Кофе,Капучино}', to_jsonb(n.new_price))
FROM new_prices n
WHERE r.restaurant_uuid = n.restaurant_uuid;

COMMIT;
