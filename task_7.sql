-- Задание 7. Единый номер телефона для всех менеджеров:
-- 8-800-2500-NNN, где NNN — порядковый номер менеджера по алфавиту,
-- начиная со 100. Старый и новый номер хранятся в массиве:
-- первый элемент — новый номер, второй — старый.
--
-- Пояснение к решению:
--
-- 1. Все шаги выполняются внутри одной транзакции: изменения структуры
--    и данных должны примениться вместе либо не примениться вовсе.
--    В PostgreSQL команды ALTER TABLE транзакционны, поэтому ROLLBACK
--    откатил бы и добавленную колонку.
--
-- 2. Таблица блокируется целиком, а не построчно: меняется её
--    структура, блокировка отдельных строк здесь не имеет смысла.
--
-- 3. Режим EXCLUSIVE выбран потому, что он конфликтует со всеми
--    режимами блокировок, кроме ACCESS SHARE. ACCESS SHARE берёт
--    обычный SELECT — значит читать таблицу другие пользователи
--    смогут. Любая запись (INSERT, UPDATE, DELETE берут ROW EXCLUSIVE,
--    SELECT ... FOR UPDATE берёт ROW SHARE) будет ждать завершения
--    транзакции. Это ровно то, что требует условие.
--    ACCESS EXCLUSIVE не подходит: он заблокировал бы и чтение тоже.
--
-- 4. Порядок шагов важен: массив собирается из нового номера и старого
--    значения manager_phone, поэтому старую колонку можно удалять
--    только после того, как её содержимое переехало в массив.
--
-- 5. ROW_NUMBER() без PARTITION BY нумерует всю таблицу подряд
--    в алфавитном порядке имён; смещение 99 даёт старт со 100.
--    Элементы массива в PostgreSQL нумеруются с единицы, поэтому
--    manager_phones[1] — новый номер, manager_phones[2] — старый.

BEGIN;

-- Запрещаем изменения таблицы, оставляя её доступной для чтения
LOCK TABLE cafe.managers IN EXCLUSIVE MODE;

-- Поле для массива номеров
ALTER TABLE cafe.managers ADD COLUMN manager_phones varchar[];

-- Новый номер по алфавитному порядку + старый номер в массив
WITH numbered AS (
    SELECT manager_uuid,
           CONCAT('8-800-2500-', 99 + ROW_NUMBER() OVER (ORDER BY manager_name)) AS new_phone
    FROM cafe.managers
)
UPDATE cafe.managers m
SET manager_phones = ARRAY[n.new_phone, m.manager_phone]
FROM numbered n
WHERE m.manager_uuid = n.manager_uuid;

-- Старое поле больше не нужно
ALTER TABLE cafe.managers DROP COLUMN manager_phone;

COMMIT;
